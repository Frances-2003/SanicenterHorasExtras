const ot = (
  n: number,
  workerId: string,
  date: string,
  start: string,
  end: string,
  minutes: number,
  reason: string,
): Overtime => ({
  id: `ot${n}`,
  code: `HE-${String(n).padStart(6, "0")}`,
  workerId,
  date,
  start,
  end,
  minutes,
  reason,
  status: "activo",
  createdAt: `${date}T${end}:00`,
});

